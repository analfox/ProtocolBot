def normalize_permit_codes(codes_str):
    """
    Разбирает строку с кодами допусков.
    Возвращает два списка: (корректные коды по возрастанию, ошибочные значения).

    Поддерживаемые форматы:
     - "1,2,5" - через запятую
     - "1 2 5" - через пробел
     - "1;2;5" - через точку с запятой
     - "1.2.5" - через точку
     - "10-15" - диапазон
     - "1,10-13,20" - комбинация
    """
    if not codes_str or not str(codes_str).strip():
        return [], []

    s = str(codes_str).strip()

    # Приводим разные разделители к запятой.
    s = re.sub(r"[;.\s]+", ",", s)
    # Диапазон: "10-15" превращаем в "10,-,15".
    s = re.sub(r"\s*-\s*", ",-,", s)

    parts = [p.strip() for p in s.split(",") if p.strip()]

    valid = []
    invalid = []

    i = 0
    while i < len(parts):
        part = parts[i]

        if part == "-":
            invalid.append(part)
            i += 1
            continue

        if part.isdigit():
            start = int(part)

            # Диапазон: число, "-", число.
            if (
                i + 2 < len(parts)
                and parts[i + 1] == "-"
                and parts[i + 2].isdigit()
            ):
                end = int(parts[i + 2])
                a, b = sorted((start, end))
                for code in range(a, b + 1):
                    if code in PERMITS:
                        valid.append(code)
                    else:
                        invalid.append(str(code))
                i += 3
                continue

            # Одиночный код.
            if start in PERMITS:
                valid.append(start)
            else:
                invalid.append(str(start))
        else:
            invalid.append(part)

        i += 1

    return sorted(set(valid)), invalid


def parse_permits(codes_str) -> str:
    """
    Преобразует строку с кодами допусков в полный текст.
    Тексты идут в порядке возрастания кодов.
    """
    codes, _invalid = normalize_permit_codes(codes_str)
    if not codes:
        return ""
    return " ".join(PERMITS[code].strip() for code in codes)


def list_permits(group: int = None) -> str:
    """
    Выводит список допусков по группам листа (или по одной группе).
    group=1, 2 или 3 - только эта группа; None - все три.
    """
    lines = []
    keys = [str(group)] if group in (1, 2, 3) else ["1", "2", "3"]
    for key in keys:
        if group is None:
            lines.append(f"=== ГРУППА {key} ===")
        for code in SHEET_GROUPS[key]:
            lines.append(f"  {code:2d} - {PERMITS[code].strip()}")
        if group is None:
            lines.append("")
    return "\n".join(lines).rstrip()


